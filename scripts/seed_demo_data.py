def make_pdf(lines):
    """生成一页的合法 PDF(Helvetica,xref 逐字节精确;中文需嵌字体,演示件用 ASCII 文案)"""
    ops = []
    y = 720
    for i, ln in enumerate(lines):
        size = 16 if i == 0 else 11
        esc = ln.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
        ops.append("BT /F1 %d Tf 60 %d Td (%s) Tj ET" % (size, y, esc))
        y -= 30
    stream = "\n".join(ops).encode("latin-1", "replace")
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for n, body in enumerate(objs, start=1):
        offsets.append(out.tell())
        out.write(("%d 0 obj\n" % n).encode() + body + b"\nendobj\n")
    start = out.tell()
    out.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1))
    for off in offsets:
        out.write(("%010d 00000 n \n" % off).encode())
    out.write(("trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
               % (len(objs) + 1, start)).encode())
    return out.getvalue()


